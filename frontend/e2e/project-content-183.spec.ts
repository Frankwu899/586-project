import { expect, test, type APIRequestContext } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import type { Project } from '../src/project/contracts';

const root = resolve(import.meta.dirname, '../..');
const seed = (mode: string): Project => JSON.parse(execFileSync(join(root, '.venv/bin/python'), [join(root, 'frontend/e2e/project-content-183-fixtures.py'), process.env.VIDEO_ANATOMY_E2E_DATA_DIR!, mode], { cwd: root, encoding: 'utf8' }));
const load = async (request: APIRequestContext, id: string): Promise<Project> => (await request.get(`/api/projects/${id}`)).json();

test('topic suggestions stay a preview until explicit idempotent Add to plan', async ({ page, request }) => {
  const project = seed('topics');
  expect(project.contents).toHaveLength(0); expect(project.series).toHaveLength(0);
  await page.goto(`/?project=${project.id}`);
  await page.getByRole('button', { name: 'Content plan', exact: true }).click();
  await page.getByRole('button', { name: 'Suggest topics', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Topic suggestions', exact: true });
  await expect(dialog.getByRole('heading', { name: 'A commuter topic', exact: true })).toBeVisible();
  expect((await load(request, project.id)).contents).toHaveLength(0);
  await dialog.getByRole('button', { name: 'Add to plan', exact: true }).click();
  await expect(dialog.getByText('Added to plan', { exact: true })).toBeVisible();
  const saved = await load(request, project.id);
  expect(saved.contents).toHaveLength(1); expect(saved.series).toHaveLength(0);
  expect(saved.contents[0].selection.resource_ids).toEqual([]);
  const repeat = await request.post(`/api/projects/${saved.id}/topics/${saved.topic_suggestions[0].id}/add`, { data: { expected_version: saved.version } });
  expect(repeat.ok()).toBeTruthy(); expect((await repeat.json()).contents).toHaveLength(1);
});

test('original Video starts without project references and explicit reference controls do not analyze', async ({ page, request }) => {
  const project = seed('original');
  expect(project.selection.resource_ids).toHaveLength(1);
  await page.goto(`/?project=${project.id}`);
  await page.getByRole('button', { name: 'Plan a video', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'Plan a video', exact: true });
  await create.getByLabel('Title', { exact: true }).fill('An original standalone Video');
  await create.getByRole('button', { name: 'Create video', exact: true }).click();
  let saved = await load(request, project.id);
  const video = saved.contents.find(item => item.title === 'An original standalone Video')!;
  expect(video.series_id).toBeNull(); expect(video.selection.resource_ids).toEqual([]);
  await page.getByRole('button', { name: 'Write a direction', exact: true }).click();
  const editor = page.getByRole('form', { name: 'Write a direction', exact: true });
  await editor.getByLabel('Title', { exact: true }).fill('An original direction');
  await editor.getByLabel('Concept', { exact: true }).fill('A human-authored original introduction.');
  await editor.getByRole('button', { name: 'Save direction', exact: true }).click();
  await page.getByRole('button', { name: 'Approve direction', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Production', exact: true })).toBeVisible();
  saved = await load(request, project.id); const approved = saved.contents.find(item => item.id === video.id)!;
  expect(approved.approved_direction_id).toBeTruthy();
  await page.getByRole('button', { name: 'Create series', exact: true }).click();
  const seriesDialog = page.getByRole('dialog', { name: 'Create series', exact: true });
  await seriesDialog.getByLabel('Title', { exact: true }).fill('Optional grouping');
  await seriesDialog.getByRole('button', { name: 'Create series', exact: true }).click();
  saved = await load(request, project.id); const series = saved.series.at(-1)!;
  await page.getByText('Organize this video', { exact: true }).click();
  await page.locator('.va-video-group').getByLabel('Series', { exact: true }).selectOption(series.id);
  await page.getByRole('button', { name: 'Move video', exact: true }).click();
  await expect.poll(async () => (await load(request, project.id)).contents.find(item => item.id === video.id)?.series_id).toBe(series.id);
  saved = await load(request, project.id);
  expect(saved.contents.find(item => item.id === video.id)?.approved_direction_id).toBe(approved.approved_direction_id);
  await page.getByText('References (0)', { exact: true }).click();
  await page.getByRole('button', { name: 'Use selected project references', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Use no references', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Use no references', exact: true }).click();
  await expect.poll(async () => (await load(request, project.id)).contents.find(item => item.id === video.id)?.selection.resource_ids).toEqual([]);
  saved = await load(request, project.id); expect(saved.jobs).toEqual([]); expect(saved.active_content_id).toBe(video.id);
});

test('explicit insight adoption merges a saved draft and retains exact sources without approving them', async ({ page, request }) => {
  const project = seed('inspiration');
  await page.goto(`/?project=${project.id}`);
  await expect(page.getByRole('heading', { name: 'Reference inspiration', exact: true })).toBeVisible();
  expect((await load(request, project.id)).contents.find(item => item.id === 'content_browsed_video')?.directions).toEqual([]);
  await page.getByRole('button', { name: 'Use as a direction draft', exact: true }).click();
  const editor = page.getByRole('form', { name: 'Write a direction', exact: true });
  await expect(editor.getByLabel('Concept', { exact: true })).toHaveValue('Existing manual concept.\n\nUse a simple commuter demonstration.');
  await expect(editor.getByLabel('Use linked inspiration references for this video', { exact: true })).toBeChecked();
  await editor.getByLabel('Title', { exact: true }).fill('An insight-linked direction');
  await editor.getByRole('button', { name: 'Save direction', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'An insight-linked direction', exact: true })).toBeVisible();
  let saved = await load(request, project.id);
  const video = saved.contents.find(item => item.id === 'content_browsed_video')!;
  const direction = video.directions.at(-1)!;
  expect(video.selection.resource_ids).toEqual(['resource_legacy_reference']);
  expect(video.approved_direction_id).toBeNull();
  expect(direction.sources[0]).toMatchObject({ resource_id: 'resource_legacy_reference', evidence_revision: 2, event_id: 'visual_corrected', start_seconds: 3, end_seconds: 3 });
  expect(saved.resources[0].evidence.at(-1)?.reviewed).toBe(false);
  await page.getByRole('button', { name: 'Approve direction', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Review the corrected evidence');
  saved = await load(request, project.id); expect(saved.contents.find(item => item.id === video.id)?.approved_direction_id).toBeNull();
  const reviewed = await request.post(`/api/projects/${saved.id}/resources/resource_legacy_reference/evidence/review`, { data: { expected_version: saved.version } });
  expect(reviewed.ok()).toBeTruthy();
  await page.reload();
  await page.getByRole('button', { name: 'Approve direction', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Production', exact: true })).toBeVisible();
  saved = await load(request, project.id); expect(saved.contents.find(item => item.id === video.id)?.directions.at(-1)?.sources[0].evidence_revision).toBe(2);
});
