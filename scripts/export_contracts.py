#!/usr/bin/env python3
"""Export authoritative Pydantic contracts; --check detects committed drift."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.models import AnalysisResult, TaskState  # noqa: E402


def exports():
    for suffix, model in (("task-state", TaskState), ("analysis", AnalysisResult)):
        schema = model.model_json_schema(mode="serialization")
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        schema["$id"] = f"https://example.invalid/video-anatomy/contracts/v0.3.{suffix}.schema.json"
        schema["$comment"] = "Generated by scripts/export_contracts.py from backend/app/models.py. Cross-record references, interval semantics and workflow gates also require runtime validation."
        yield ROOT / f"contracts/v0.3.{suffix}.schema.json", json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for path, contents in exports():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
            print(f"Wrote {path.relative_to(ROOT)}")
    if mismatches:
        print("Contract drift: " + ", ".join(mismatches), file=sys.stderr)
        return 1
    if args.check:
        print("Generated schemas match authoritative Pydantic models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
